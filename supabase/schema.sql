-- APEXCOACH server setup: chat v2 + accounts, points & leaderboard.
-- Run this whole file once in the Supabase SQL editor (safe to run again).
-- The public (anon/publishable) key can only call the apex_* functions below;
-- it cannot read, list or change any table directly.

-- =====================================================================
-- CHAT (rooms bound to device keys, single-use invite codes)
-- =====================================================================
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.apex_rooms (
  room text primary key check (room ~ '^[A-Z0-9]{12}$'),
  coach_key_hash text not null,
  client_key_hash text,
  created_at timestamptz not null default now()
);

create table if not exists public.apex_messages (
  id bigint generated by default as identity primary key,
  room text not null references public.apex_rooms(room) on delete cascade,
  sender text not null check (sender in ('coach', 'client')),
  sender_name text check (char_length(sender_name) <= 60),
  body text not null check (char_length(body) between 1 and 2000),
  plan_id text check (plan_id ~ '^[A-Za-z0-9_-]{1,64}$'),
  created_at timestamptz not null default now()
);
create index if not exists apex_messages_room_idx on public.apex_messages (room, created_at);

alter table public.apex_rooms enable row level security;
alter table public.apex_messages enable row level security;
revoke all on public.apex_rooms, public.apex_messages from anon, authenticated;

-- Helper: which role does this device key have in this room? (internal only)
create or replace function public.apex_role(p_room text, p_key text)
returns text language sql stable security definer set search_path = public, extensions as $$
  select case
    when r.coach_key_hash = encode(extensions.digest(p_key, 'sha256'), 'hex') then 'coach'
    when r.client_key_hash = encode(extensions.digest(p_key, 'sha256'), 'hex') then 'client'
  end
  from public.apex_rooms r where r.room = p_room;
$$;

-- Coach registers a new room with its device key
create or replace function public.apex_create_room(p_room text, p_key text)
returns boolean language plpgsql security definer set search_path = public, extensions as $$
begin
  if p_key !~ '^[0-9a-f]{64}$' then raise exception 'invalid code'; end if;
  insert into public.apex_rooms (room, coach_key_hash)
  values (p_room, encode(extensions.digest(p_key, 'sha256'), 'hex'));
  return true;
exception when unique_violation then
  raise exception 'room exists';
end $$;

-- Client claims the single-use invite. Later devices with the same code are refused.
create or replace function public.apex_join_room(p_room text, p_key text)
returns text language plpgsql security definer set search_path = public, extensions as $$
declare
  r public.apex_rooms;
  h text := encode(extensions.digest(p_key, 'sha256'), 'hex');
begin
  if p_key !~ '^[0-9a-f]{64}$' then raise exception 'invalid code'; end if;
  select * into r from public.apex_rooms where room = p_room for update;
  if not found then raise exception 'invalid code'; end if;
  if r.coach_key_hash = h then return 'coach'; end if;
  if r.client_key_hash is null then
    update public.apex_rooms set client_key_hash = h where room = p_room;
    return 'client';
  end if;
  if r.client_key_hash = h then return 'client'; end if;
  raise exception 'invalid code';
end $$;

-- Send a message. The server decides the sender role from the key. Max 30 messages per minute per room.
create or replace function public.apex_send(p_room text, p_key text, p_sender_name text, p_body text, p_plan_id text default null)
returns public.apex_messages language plpgsql security definer set search_path = public, extensions as $$
declare
  v_role text := public.apex_role(p_room, p_key);
  v_row public.apex_messages;
begin
  if v_role is null then raise exception 'not allowed'; end if;
  if (select count(*) from public.apex_messages
      where room = p_room and created_at > now() - interval '1 minute') >= 30 then
    raise exception 'rate limit';
  end if;
  insert into public.apex_messages (room, sender, sender_name, body, plan_id)
  values (p_room, v_role, left(coalesce(p_sender_name, ''), 60), p_body, nullif(p_plan_id, ''))
  returning * into v_row;
  return v_row;
end $$;

-- Read the latest 200 messages of a room (only for its coach or client device)
create or replace function public.apex_history(p_room text, p_key text)
returns setof public.apex_messages language plpgsql stable security definer set search_path = public, extensions as $$
begin
  if public.apex_role(p_room, p_key) is null then raise exception 'not allowed'; end if;
  return query
    select * from (
      select * from public.apex_messages where room = p_room order by created_at desc limit 200
    ) recent order by created_at asc;
end $$;

revoke execute on function public.apex_role(text, text) from public, anon, authenticated;
revoke execute on function public.apex_create_room(text, text) from public;
revoke execute on function public.apex_join_room(text, text) from public;
revoke execute on function public.apex_send(text, text, text, text, text) from public;
revoke execute on function public.apex_history(text, text) from public;
grant execute on function public.apex_create_room(text, text) to anon, authenticated;
grant execute on function public.apex_join_room(text, text) to anon, authenticated;
grant execute on function public.apex_send(text, text, text, text, text) to anon, authenticated;
grant execute on function public.apex_history(text, text) to anon, authenticated;

-- =====================================================================
-- ACCOUNTS, POINTS & LEADERBOARD
-- Uses Supabase Auth (email + password, email confirmation required).
-- Points are calculated here on the server with limits, so they can't be faked.
-- Other users only ever see display name, goal, workouts and points — never emails.
-- =====================================================================
create table if not exists public.apex_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 2 and 30 and display_name !~ '[<>]'),
  objective text not null default 'bodybuilding' check (objective in ('bodybuilding', 'athlete')),
  points integer not null default 0 check (points >= 0),
  workouts integer not null default 0 check (workouts >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.apex_activity (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  ref text not null check (ref ~ '^[A-Za-z0-9_-]{1,64}$'),
  kind text not null check (kind in ('strength', 'run', 'hiit', 'test')),
  sets integer,
  duration_sec integer,
  distance_km numeric(6, 2),
  points integer not null,
  created_at timestamptz not null default now(),
  unique (user_id, ref)
);
create index if not exists apex_activity_user_time_idx on public.apex_activity (user_id, created_at);
create index if not exists apex_activity_time_idx on public.apex_activity (created_at);

alter table public.apex_profiles enable row level security;
alter table public.apex_activity enable row level security;
revoke all on public.apex_profiles, public.apex_activity from anon, authenticated;

-- Every new sign-up gets a profile (name and goal come from the sign-up form)
create or replace function public.apex_handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_name text := trim(left(regexp_replace(coalesce(new.raw_user_meta_data ->> 'display_name', ''), '[<>]', '', 'g'), 30));
begin
  if char_length(v_name) < 2 then v_name := 'Athlete ' || left(new.id::text, 4); end if;
  insert into public.apex_profiles (id, display_name, objective)
  values (new.id, v_name, case when new.raw_user_meta_data ->> 'objective' = 'athlete' then 'athlete' else 'bodybuilding' end)
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists apex_on_auth_user_created on auth.users;
create trigger apex_on_auth_user_created after insert on auth.users
  for each row execute function public.apex_handle_new_user();

-- Signed in AND email confirmed (otherwise null)
create or replace function public.apex_confirmed_uid()
returns uuid language sql stable security definer set search_path = public as $$
  select u.id from auth.users u where u.id = auth.uid() and u.email_confirmed_at is not null;
$$;

create or replace function public.apex_my_profile()
returns setof public.apex_profiles language sql stable security definer set search_path = public as $$
  select * from public.apex_profiles where id = public.apex_confirmed_uid();
$$;

create or replace function public.apex_update_profile(p_display_name text, p_objective text)
returns void language plpgsql security definer set search_path = public as $$
declare v_uid uuid := public.apex_confirmed_uid();
begin
  if v_uid is null then raise exception 'not allowed'; end if;
  if p_objective not in ('bodybuilding', 'athlete') then raise exception 'invalid objective'; end if;
  update public.apex_profiles set display_name = trim(p_display_name), objective = p_objective where id = v_uid;
end $$;

-- Record a finished activity. The server decides if it counts and what it is worth.
-- Limits: max 8 per 24 hours, minimum length per type, realistic running speed, no duplicates.
create or replace function public.apex_record_workout(p_ref text, p_kind text, p_sets integer, p_duration_sec integer, p_distance_km numeric)
returns table (points integer, workouts integer) language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := public.apex_confirmed_uid();
  v_points integer;
begin
  if v_uid is null then raise exception 'not allowed'; end if;
  if exists (select 1 from public.apex_activity a where a.user_id = v_uid and a.ref = p_ref) then raise exception 'duplicate'; end if;
  if (select count(*) from public.apex_activity a where a.user_id = v_uid and a.created_at > now() - interval '24 hours') >= 8 then
    raise exception 'daily limit';
  end if;
  if p_kind = 'strength' and coalesce(p_sets, 0) >= 3 and coalesce(p_duration_sec, 0) >= 300 then
    v_points := 100 + least(p_sets, 40) * 5;
  elsif p_kind = 'run' and coalesce(p_distance_km, 0) >= 0.5 and coalesce(p_duration_sec, 0) >= 180
        and p_distance_km / (p_duration_sec / 3600.0) <= 25 then
    v_points := 50 + round(least(p_distance_km, 42) * 10);
  elsif p_kind = 'hiit' and coalesce(p_duration_sec, 0) >= 120 then
    v_points := 60;
  elsif p_kind = 'test' then
    v_points := 30;
  else
    raise exception 'not eligible';
  end if;
  insert into public.apex_activity (user_id, ref, kind, sets, duration_sec, distance_km, points)
  values (v_uid, p_ref, p_kind, p_sets, p_duration_sec, p_distance_km, v_points);
  update public.apex_profiles pr set points = pr.points + v_points, workouts = pr.workouts + 1 where pr.id = v_uid;
  return query select pr.points, pr.workouts from public.apex_profiles pr where pr.id = v_uid;
end $$;

-- Leaderboard: ranked by workouts (then points), this week or all time. Top 100 plus you.
create or replace function public.apex_leaderboard(p_period text default 'week')
returns table (rank bigint, display_name text, objective text, workouts bigint, points bigint, is_me boolean)
language sql stable security definer set search_path = public as $$
  with me as (select public.apex_confirmed_uid() as uid),
  week as (
    select a.user_id, count(*) as cnt, sum(a.points) as pts
    from public.apex_activity a where a.created_at > now() - interval '7 days' group by a.user_id
  ),
  totals as (
    select p.id, p.display_name, p.objective,
      case when p_period = 'all' then p.workouts::bigint else coalesce(w.cnt, 0) end as workouts,
      case when p_period = 'all' then p.points::bigint else coalesce(w.pts, 0)::bigint end as points
    from public.apex_profiles p left join week w on w.user_id = p.id
    where (select uid from me) is not null
  ),
  ranked as (
    select dense_rank() over (order by t.workouts desc, t.points desc) as rnk, t.*
    from totals t where t.workouts > 0 or t.id = (select uid from me)
  )
  select r.rnk, r.display_name, r.objective, r.workouts, r.points, r.id = (select uid from me)
  from ranked r where r.rnk <= 100 or r.id = (select uid from me)
  order by r.rnk, r.display_name limit 101;
$$;

-- Delete your own account (profile and activity are removed with it)
create or replace function public.apex_delete_account()
returns void language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid();
begin
  if v_uid is null then raise exception 'not allowed'; end if;
  delete from auth.users where id = v_uid;
end $$;

