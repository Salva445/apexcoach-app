-- APEXCOACH chat v2. Run once in the Supabase SQL editor.
-- The public (anon/publishable) key can ONLY call the four apex_* functions below.
-- It cannot read, list or change the tables directly.
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.apex_rooms (
  room text primary key check (room ~ '^[A-Z0-9]{12}$'),
  coach_key_hash text not null,
  client_key_hash text,
  created_at timestamptz not null default now()
);

create table if not exists public.apex_messages (
  id bigint generated by default as identity primary key,
  room text not null references public.apex_rooms(room) on delete cascade,
  sender text not null check (sender in ('coach', 'client')),
  sender_name text check (char_length(sender_name) <= 60),
  body text not null check (char_length(body) between 1 and 2000),
  plan_id text check (plan_id ~ '^[A-Za-z0-9_-]{1,64}$'),
  created_at timestamptz not null default now()
);
create index if not exists apex_messages_room_idx on public.apex_messages (room, created_at);

alter table public.apex_rooms enable row level security;
alter table public.apex_messages enable row level security;
revoke all on public.apex_rooms, public.apex_messages from anon, authenticated;

-- Helper: which role does this device key have in this room? (internal only)
create or replace function public.apex_role(p_room text, p_key text)
returns text language sql stable security definer set search_path = public, extensions as $$
  select case
    when r.coach_key_hash = encode(extensions.digest(p_key, 'sha256'), 'hex') then 'coach'
    when r.client_key_hash = encode(extensions.digest(p_key, 'sha256'), 'hex') then 'client'
  end
  from public.apex_rooms r where r.room = p_room;
$$;

-- Coach registers a new room with its device key
create or replace function public.apex_create_room(p_room text, p_key text)
returns boolean language plpgsql security definer set search_path = public, extensions as $$
begin
  if p_key !~ '^[0-9a-f]{64}$' then raise exception 'invalid code'; end if;
  insert into public.apex_rooms (room, coach_key_hash)
  values (p_room, encode(extensions.digest(p_key, 'sha256'), 'hex'));
  return true;
exception when unique_violation then
  raise exception 'room exists';
end $$;

-- Client claims the single-use invite. Later devices with the same code are refused.
create or replace function public.apex_join_room(p_room text, p_key text)
returns text language plpgsql security definer set search_path = public, extensions as $$
declare
  r public.apex_rooms;
  h text := encode(extensions.digest(p_key, 'sha256'), 'hex');
begin
  if p_key !~ '^[0-9a-f]{64}$' then raise exception 'invalid code'; end if;
  select * into r from public.apex_rooms where room = p_room for update;
  if not found then raise exception 'invalid code'; end if;
  if r.coach_key_hash = h then return 'coach'; end if;
  if r.client_key_hash is null then
    update public.apex_rooms set client_key_hash = h where room = p_room;
    return 'client';
  end if;
  if r.client_key_hash = h then return 'client'; end if;
  raise exception 'invalid code';
end $$;

-- Send a message. The server decides the sender role from the key. Max 30 messages per minute per room.
create or replace function public.apex_send(p_room text, p_key text, p_sender_name text, p_body text, p_plan_id text default null)
returns public.apex_messages language plpgsql security definer set search_path = public, extensions as $$
declare
  v_role text := public.apex_role(p_room, p_key);
  v_row public.apex_messages;
begin
  if v_role is null then raise exception 'not allowed'; end if;
  if (select count(*) from public.apex_messages
      where room = p_room and created_at > now() - interval '1 minute') >= 30 then
    raise exception 'rate limit';
  end if;
  insert into public.apex_messages (room, sender, sender_name, body, plan_id)
  values (p_room, v_role, left(coalesce(p_sender_name, ''), 60), p_body, nullif(p_plan_id, ''))
  returning * into v_row;
  return v_row;
end $$;

-- Read the latest 200 messages of a room (only for its coach or client device)
create or replace function public.apex_history(p_room text, p_key text)
returns setof public.apex_messages language plpgsql stable security definer set search_path = public, extensions as $$
begin
  if public.apex_role(p_room, p_key) is null then raise exception 'not allowed'; end if;
  return query
    select * from (
      select * from public.apex_messages where room = p_room order by created_at desc limit 200
    ) recent order by created_at asc;
end $$;

revoke execute on function public.apex_role(text, text) from public, anon, authenticated;
revoke execute on function public.apex_create_room(text, text) from public;
revoke execute on function public.apex_join_room(text, text) from public;
revoke execute on function public.apex_send(text, text, text, text, text) from public;
revoke execute on function public.apex_history(text, text) from public;
grant execute on function public.apex_create_room(text, text) to anon, authenticated;
grant execute on function public.apex_join_room(text, text) to anon, authenticated;
grant execute on function public.apex_send(text, text, text, text, text) to anon, authenticated;
grant execute on function public.apex_history(text, text) to anon, authenticated;
